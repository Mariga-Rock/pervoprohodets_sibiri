"""
Советник. Контекстные подсказки по состоянию отряда.

Возвращает строку-совет или None. Не показывает чаще одного раза
в 3 дня. Приоритет — самые острые проблемы.
"""

# Как часто можно показывать совет (в днях).
ADVISOR_COOLDOWN_DAYS = 3


def get_advisor_hint(run):
    """
    Возвращает совет по текущему состоянию Run или None.
    Обновляет run.last_advisor_day, если совет был показан.
    """
    # Кулдаун
    if run.day - (run.last_advisor_day or 0) < ADVISOR_COOLDOWN_DAYS:
        return None

    hint = _pick_hint(run)

    if hint:
        run.last_advisor_day = run.day
    return hint


def _pick_hint(run):
    """Выбирает самый приоритетный совет."""

    # ---- КРИЗИСЫ ----

    # 1. Цинга активна
    if run.scurvy_active:
        return (
            "🫐 Цинга. Варить хвойный отвар или собирать ягоды. "
            "Без витамина — смерть."
        )

    # 2. Витамин низкий
    if run.vit_c < 40:
        if run.season in (1, 2):
            return (
                "🍋 Витамин падает. Рыба, ягоды или хвойный отвар. "
                "Скоро цинга."
            )
        return (
            "🍋 Витамин падает. Хвойный отвар — единственный источник."
        )

    # 3. Гангрена — нужно срочно
    if any(t.alive and t.gangrene for t in run.travelers):
        return "☠ Гангрена. Ампутация или смерть. Нужен ланцет."

    # 4. Стрела в теле
    if any(t.alive and t.arrow_stuck for t in run.travelers):
        return "🩹 Стрела в теле. Операция ланцетом или гангрена."

    # 5. Раненые и нет трав
    if run.wounded > 0 and run.inventory.get("herbs", 0) == 0:
        return (
            "🩹 Есть раненые, а трав нет. Собирайте травы — "
            "они ускоряют выздоровление."
        )

    # 6. Еда на исходе
    food_total = (run.flour or 0) + (run.fish or 0) + (run.meat or 0)
    if food_total < run.squad_size * 3:
        return (
            "🍖 Провізии почти нет. Охоться или рыбачь. "
            "Иначе — голод."
        )

    # ---- ВОЗМОЖНОСТИ ----

    # 7. Пушнина накопилась
    fur = run.inventory.get("fur", 0)
    if fur >= 20:
        return (
            f"💰 Пушнина: {fur}. Продай купцам или отправь в Москву."
        )

    # 8. Грамот хватает на город
    if run.charters >= 5 and run.cities_count == 0:
        return "🏙 5 грамот. Можно основать первый город."

    # 9. Ясак не собран, а племена есть
    if run.yasak_count < 5 and run.day > 30:
        return (
            "📜 Ясак собирается с пяти племён: "
            "татары, вогулы, остяки, селькупы, самоядь."
        )

    # ---- СОСТОЯНИЕ ----

    # 10. Мораль падает
    if run.morale < 40:
        return "🔥 Мораль низкая. Отдохни у костра или помолись."

    # 11. Дисциплина падает
    if run.discipline < 30:
        return "⚔ Дисциплина падает. Наказание или казнь — иначе бунт."

    # 12. Зима
    if run.season == 3:
        return (
            "❄️ Зима. Отряд стоит. Расход еды увеличен. "
            "Идти нельзя."
        )

    # ---- ОБУЧЕНИЕ ----

    # 13. Первый день
    if run.day == 1:
        return (
            "🛤 100 вёрст до Мангазеи. Каждый день важен. "
            "Следи за провизией и витамином."
        )

    # 14. Первые дни
    if run.day <= 5:
        return (
            "🧭 В первые дни отряд ещё не освоился. "
            "Осторожнее с тайгой."
        )

    return None
