"""
Советник. Контекстные подсказки по состоянию отряда.

Возвращает строку-совет или None. Не показывает чаще одного раза
в 3 дня. Приоритет — самые острые проблемы.
"""

# Как часто можно показывать совет (в днях).
ADVISOR_COOLDOWN_DAYS = 3


def get_advisor_hint(run):
    """
    Возвращает совет по текущему состоянию Run или None.
    Обновляет run.last_advisor_day, если совет был показан.
    """
    # Кулдаун — не чаще одного раза в 3 дня.
    if run.day - (run.last_advisor_day or 0) < ADVISOR_COOLDOWN_DAYS:
        return None

    hint = None

    # 1. Цинга — самый острый кризис.
    if run.vit_c < 30:
        hint = (
            "🫐 Цинга близко. Клюква, хвоя, черемша — срочно. "
            "Иначе дёсны начнут кровить."
        )

    # 2. Кончилась еда.
    elif run.flour + run.fish + run.meat < run.squad_size * 4:
        hint = (
            "🍖 Провізии почти нет. Ловите рыбу, охотьтесь, "
            "ищите съестное в тайге."
        )

    # 3. Мука кончается — остальное надо добывать.
    elif run.flour < 60 and run.fish == 0:
        hint = (
            "🌾 Мука кончается — а это запас Строгановых, "
            "пополнить его негде. Ловите рыбу или охотьтесь."
        )

    # 4. Рыба.
    elif run.fish == 0 and run.day > 5:
        hint = (
            "🐟 Рыба — лучший запас в пути: и еда, и витамин C. "
            "Кнопка «Рыбалка» — рабочий день."
        )

    # 5. Мясо.
    elif run.meat == 0 and run.day > 5 and run.squad_size >= 3:
        hint = (
            "🍖 Охота даёт мясо и пушнину. Чем больше людей — "
            "тем больше добыча."
        )

    # 6. Раненые.
    elif run.wounded > 0 and run.inventory.get("herbs", 0) == 0:
        hint = (
            "🩹 Есть раненые, а трав нет. Соберите травы — "
            "они ускоряют выздоровление."
        )

    # 7. Дисциплина падает.
    elif run.discipline < 30:
        hint = (
            "⚔ Дисциплина падает. Порка или казнь вернут порядок, "
            "но ударят по морали."
        )

    # 8. Первый день.
    elif run.day == 1:
        hint = (
            "🛤 100 вёрст до Мангазеи. Каждый день пути — "
            "3 версты. Следите за провизией."
        )

    # 9. Мораль падает.
    elif run.morale < 40:
        hint = (
            "🔥 Мораль низкая. Отдых у костра или молебен "
            "вернут дух отряду."
        )

    if hint:
        run.last_advisor_day = run.day
    return hint
