"""
Расширения Flask, вынесенные в отдельный файл.

Зачем отдельный файл:
    SQLAlchemy и другие расширения должны быть созданы ДО того, как их
    начнут импортировать модели и маршруты. Если создать db в app.py,
    то models.py не сможет импортировать db без циклического импорта.

Правило:
    Этот файл НИКОГО не импортирует. Его импортируют все остальные.
"""

from flask_sqlalchemy import SQLAlchemy

# Единственный экземпляр SQLAlchemy на всё приложение.
# Все модели наследуются от db.Model.
db = SQLAlchemy()

# session_options передаются в sessionmaker при создании сессии.
# expire_on_commit=False:
#   после db.session.commit() объекты НЕ помечаются как "просроченные",
#   их атрибуты можно читать вне app_context (нужно для тестовых скриптов
#   и для возврата ORM-объектов из функций).
db = SQLAlchemy(session_options={"expire_on_commit": False})
